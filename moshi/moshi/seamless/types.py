"""Transport-neutral data types for seamless PersonaPlex installation."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any

import numpy as np


class ControllerPhase(str, Enum):
    IDLE = "idle"
    ACTIVE = "active"
    COMPACTING = "compacting"
    PREFILLING = "prefilling"
    CATCHING_UP = "catching_up"
    READY = "ready"
    SWAPPING = "swapping"
    CLOSED = "closed"


@dataclass(slots=True)
class ControllerConfig:
    """Runtime policy, expressed in PersonaPlex codec frames."""

    context_capacity_frames: int = 3000
    trigger_reserve_frames: int = 1400
    replay_batch_frames: int = 64
    switch_max_lag_frames: int = 2
    safe_silence_frames: int = 3
    silence_rms_threshold: float = 0.004
    force_switch_after_s: float = 8.0
    install_timeout_s: float = 180.0
    ledger_max_frames: int = 20_000
    codec_convergence_frames: int = 16
    decoder_convergence_frames: int = 16
    auto_trigger_enabled: bool = True
    memory_heading: str = "conversation_memory"

    def __post_init__(self) -> None:
        if self.context_capacity_frames <= 0:
            raise ValueError("context_capacity_frames must be positive")
        if not 0 < self.trigger_reserve_frames < self.context_capacity_frames:
            raise ValueError("trigger_reserve_frames must be inside context capacity")
        if self.replay_batch_frames <= 0:
            raise ValueError("replay_batch_frames must be positive")
        if self.switch_max_lag_frames < 0:
            raise ValueError("switch_max_lag_frames cannot be negative")
        if self.safe_silence_frames < 0:
            raise ValueError("safe_silence_frames cannot be negative")
        if self.force_switch_after_s < 0 or self.install_timeout_s <= 0:
            raise ValueError("invalid switch/install timeout")
        if self.ledger_max_frames < self.context_capacity_frames:
            raise ValueError("ledger_max_frames must cover at least one context")
        if self.codec_convergence_frames < 0:
            raise ValueError("codec_convergence_frames cannot be negative")
        if self.decoder_convergence_frames < 0:
            raise ValueError("decoder_convergence_frames cannot be negative")

    @property
    def trigger_at_context_frame(self) -> int:
        return self.context_capacity_frames - self.trigger_reserve_frames


@dataclass(slots=True)
class DuplexFrame:
    """One exact replay unit at the PersonaPlex 12.5 Hz LM frame rate.

    ``assistant_tokens`` are the target-position text + assistant audio codes
    generated by the active model for this input frame. They are intentionally
    distinct from the delayed tokens emitted to the browser on the same wall
    clock step.
    """

    seq: int
    pcm: np.ndarray
    user_codes: np.ndarray
    assistant_tokens: np.ndarray
    target_digest: str
    played: bool = False
    played_rms: float | None = None
    played_pcm: np.ndarray | None = None

    def __post_init__(self) -> None:
        self.pcm = np.asarray(self.pcm, dtype=np.float32).reshape(-1).copy()
        self.user_codes = np.asarray(self.user_codes, dtype=np.int64).reshape(-1).copy()
        self.assistant_tokens = (
            np.asarray(self.assistant_tokens, dtype=np.int64).reshape(-1).copy()
        )
        if self.seq < 0:
            raise ValueError("frame seq cannot be negative")
        if self.user_codes.shape != (8,):
            raise ValueError(f"expected 8 user codes, got {self.user_codes.shape}")
        if self.assistant_tokens.shape != (9,):
            raise ValueError(
                f"expected text + 8 assistant codes, got {self.assistant_tokens.shape}"
            )
        if self.played_pcm is not None:
            self.played_pcm = (
                np.asarray(self.played_pcm, dtype=np.float32).reshape(-1).copy()
            )


@dataclass(slots=True)
class StepResult:
    frame: DuplexFrame
    output_pcm: np.ndarray | None
    output_text: str
    emitted_seq: int | None
    context_frames: int

    def __post_init__(self) -> None:
        if self.output_pcm is not None:
            self.output_pcm = np.asarray(self.output_pcm, dtype=np.float32).reshape(-1)


@dataclass(frozen=True, slots=True)
class ReplayResult:
    start_seq: int
    end_seq: int
    frames: int
    user_code_mismatches: int
    target_mismatches: int
    user_code_values_differ: int = 0
    user_codebook_mismatches: tuple[int, ...] = ()
    last_user_mismatch_seq: int | None = None
    decoder_frames_compared: int = 0
    decoder_mismatches: int = 0
    last_decoder_mismatch_seq: int | None = None
    last_decoder_compared_seq: int | None = None


@dataclass(frozen=True, slots=True)
class CompactRequest:
    session_id: str
    request_id: str
    parent_version: int
    cutoff_hint_seq: int
    previous_memory: str
    role_prompt: str
    ledger_digest: str


@dataclass(frozen=True, slots=True)
class CompactResult:
    request_id: str
    parent_version: int
    cutoff_seq: int
    memory: str
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class SwapRecord:
    version: int
    old_active: str
    new_active: str
    cutoff_seq: int
    replayed_through_seq: int
    forced_boundary: bool
    memory: str
    request_id: str
    timings: dict[str, float] = field(default_factory=dict)
